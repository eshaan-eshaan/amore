// Generates shop.html (the one template behind every product, collection, search, checkout and placeholder page)
// from index.html, so the announcement bar, header, menu, drawers and footer are exactly the homepage's.
//
//   node tools/build-shop.mjs         write shop.html
//   node tools/build-shop.mjs --check exit 1 if shop.html is out of date (used by `npm run verify`)
//
// Re-run it after changing the shared chrome in index.html.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const index = readFileSync(join(ROOT, 'index.html'), 'utf8');

const slice = (from, to) => {
  const a = index.indexOf(from);
  const b = to ? index.indexOf(to) : index.length;
  if (a < 0 || b < 0) throw new Error(`marker not found in index.html: ${a < 0 ? from : to}`);
  return index.slice(a, b);
};
// nested routes need root-relative URLs for everything the chrome loads
const absolute = (html) => html.replace(/(src|href|srcset)="(assets|css|js|fonts)\//g, '$1="/$2/');

const chrome = absolute(slice('<!-- ───────────── announcement bar', '<!-- ───────────── page'));
const footer = absolute(slice('<!-- ───────────── footer', '</body>'));

const html = `<!doctype html>
<!-- Generated by tools/build-shop.mjs from index.html. Edit the chrome in index.html, not here. -->
<html lang="en" dir="ltr">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>AMORE</title>
  <meta name="description" content="AMORE, The Fragrance Collection: ten distinct scent identities. Passion in every drop.">
  <meta name="robots" content="noindex, nofollow">
  <link rel="preload" href="/fonts/jost/jost-latin-normal.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="stylesheet" href="/css/fonts.css">
  <link rel="icon" href="/assets/logo/favicon.png" type="image/png">
  <link rel="stylesheet" href="/css/base.css">
  <link rel="stylesheet" href="/css/chrome.css">
  <link rel="stylesheet" href="/css/brand.css">
  <link rel="stylesheet" href="/css/footer.css">
  <link rel="stylesheet" href="/css/shop.css">
  <script type="module" src="/js/shop-main.js"></script>
</head>
<body class="shop-page ltr">
<a class="skip-link" href="#main">Skip to content</a>

${chrome.trimEnd()}

<!-- ───────────── page: filled in by js/shop.js ───────────── -->
<main class="shop" id="main" tabindex="-1">
  <div class="shop-view" data-shop-view>
    <noscript><p class="shop-message">This page needs JavaScript to show the fragrances.</p></noscript>
  </div>
</main>

${footer.trimEnd()}
</body>
</html>
`;

const target = join(ROOT, 'shop.html');
if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== html) { console.error('shop.html is out of date: run `node tools/build-shop.mjs`'); process.exit(1); }
  console.log('shop.html is up to date');
} else {
  writeFileSync(target, html);
  console.log(`wrote shop.html (${html.length} bytes)`);
}
